// O mapa guarda o nome da aba (String) e a "fábrica" do painel (Supplier)
private final Map<String, Supplier<JPanel>> panelMap = new HashMap<>();
    
    
/*===============================================
   É VERIFICADO SE O ITEM ESTÁ NO FIM DA ÁRVORE
===============================================*/
    private void BATZ_DATABASEValueChanged(javax.swing.event.TreeSelectionEvent evt) {//GEN-FIRST:event_BATZ_DATABASEValueChanged
    // 1. Pega o nó que foi selecionado
javax.swing.tree.DefaultMutableTreeNode SelectionNo = (javax.swing.tree.DefaultMutableTreeNode) BATZ_DATABASE.getLastSelectedPathComponent();

// 2. Verifica se foi selecionado algo válido
if (SelectionNo == null) {
    return;
}

// 3. Verifica se é uma folha (para evitar clicar em pastas como 'Financeiro')
if (SelectionNo.isLeaf()) {
    
    // 4. Puxa o nome da seleção
    String TabName = SelectionNo.getUserObject().toString();

    // 5. Verifica se já está aberta
    int index = BATZ_TABBEDPANE.indexOfTab(TabName);

    // 6. Se a aba já existe, muda o foco para ela
    if (index != -1) {
        BATZ_TABBEDPANE.setSelectedIndex(index);
    } 
    // 7. Se não existe, cria uma nova usando o nosso Mapa
    else {
        // Verifica se o mapa conhece essa aba antes de tentar criar
        if (panelMap.containsKey(TabName)) {
            javax.swing.JPanel newPanel = panelMap.get(TabName).get();
            BATZ_TABBEDPANE.addTab(TabName, newPanel);

            int lastIndex = BATZ_TABBEDPANE.getTabCount() - 1;
            
            // Adiciona o botão de X na aba que acabou de nascer
            addCloseButtonToTab(lastIndex); 

            BATZ_TABBEDPANE.setSelectedIndex(lastIndex);
        } else {
            System.out.println("Atenção: A tela '" + TabName + "' não foi mapeada no inicializarMapa.");
        }
    }
}
               
    }
     

    
    
/*===============================================
    BOTAO DE X AO LADO DA ABA
===============================================*/
    private void addCloseButtonToTab(int index) {
        javax.swing.JPanel tabHeader = new javax.swing.JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.LEFT, 5, 0));
        tabHeader.setOpaque(false);

        javax.swing.JLabel titleLabel = new javax.swing.JLabel(BATZ_TABBEDPANE.getTitleAt(index));
        javax.swing.JButton closeButton = new javax.swing.JButton("x");
        
        closeButton.setBorder(null);
        closeButton.setContentAreaFilled(false);
        closeButton.setFocusable(false);
        closeButton.setBorderPainted(false);
        closeButton.setMargin(new java.awt.Insets(0, 5, 0, 0));
        closeButton.setCursor(new java.awt.Cursor(java.awt.Cursor.HAND_CURSOR));

        closeButton.addActionListener(e -> {
            int currentIndex = BATZ_TABBEDPANE.indexOfTabComponent(tabHeader);
            if (currentIndex != -1) {
                BATZ_TABBEDPANE.removeTabAt(currentIndex);
            }
        }); // <--- Aqui fecha o ActionListener corretamente

        tabHeader.add(titleLabel);
        tabHeader.add(closeButton);
        BATZ_TABBEDPANE.setTabComponentAt(index, tabHeader);
    }
        
        
        
        
        
