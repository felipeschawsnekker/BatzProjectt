    private void VariableSALVARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_VariableSALVARActionPerformed

        String categoria = Objects.toString(VariableComboCategoria.getSelectedItem(), "");
        String nome = VariableNome.getText();
        String unidadeMedida = Objects.toString(VariableComboUnidadeDeMedida.getSelectedItem(), "");

        if (nome.trim().isEmpty() || categoria.trim().isEmpty() || unidadeMedida.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos obrigatórios.");
            return;
            }
        ControllerCadastroDeProdutos.cadastrarProduto(nome,categoria,unidadeMedida);
        javax.swing.JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
        VariableComboCategoria.setSelectedIndex(-1);
        VariableNome.setText("");
        VariableComboUnidadeDeMedida.setSelectedIndex(-1);
        
        VariableCodigo.setText(ControllerCadastroDeProdutos.getProximoCodigo());
    }//GEN-LAST:event_VariableSALVARActionPerformed

