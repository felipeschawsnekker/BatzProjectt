    private void carregarTabela(){
        
        DefaultTableModel model = (DefaultTableModel) VariableTableProdutosCadastrados.getModel();
        model.setRowCount(0);
        
        List<Product> produtos= ControllerCadastroDeProdutos.getListaDeProdutos();
        for(Product produto:produtos){
            model.addRow(new Object[]{
            produto.getCodigo(),
            produto.getNome(),
            produto.getCategoria(),
            produto.getUnidadeDeMedida()
            });
        }
        
    }
    
